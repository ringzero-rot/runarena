export const COACH_NAME = COACHES.zaap.name; // legacy default (kept for imports)
export const COACH_ICON = COACHES.zaap.icon;

export function getCoach(id) {
  return COACHES[id] || COACHES.zaap;
}

function pick(arr, seed) { return arr[Math.abs(seed) % arr.length]; }
function fill(s, d) {
  return s
    .replace('{name}', d.name || 'เธอ')
    .replace('{rank}', String(d.rank ?? '-'))
    .replace('{rival}', d.rival || 'คู่ปรับ')
    .replace('{streak}', String(d.streak ?? 0))
    .replace('{days}', String(Math.max(1, Math.floor(d.lastRunDays ?? 1))))
    .replace('{route}', d.routeName || 'สนามนี้');
}

/**
 * Contextual coach line. For 'daily' it personalises based on your real state
 * (long absence / hot streak / cold streak).
 * @param {string} ctx
 * @param {CoachData} [data]
 * @param {number} [seed]
 * @param {string} [coachId]
 * @returns {string}
 */
export function coachSay(ctx, data = {}, seed = Date.now(), coachId = 'zaap') {
  const c = getCoach(coachId);
  let key = ctx;
  if (ctx === 'daily') {
    if ((data.lastRunDays ?? 0) >= 2) key = 'idle';
    else if ((data.streak ?? 0) >= 7) key = 'streakHi';
    else if ((data.streak ?? 0) <= 2 && seed % 2 === 0) key = 'streakLo';
  }
  const pool = c.pools[key] || c.pools.daily;
  return fill(pick(pool, seed), data);
}
